"""Actual tiny synthetic optimizations through all six neural conditions and both studies.

No industrial benchmark fits or scientific results are generated by these tests.
"""
from copy import deepcopy
from pathlib import Path
import json
import numpy as np
import pandas as pd
import torch
from cora_maple.config import ROOT, BASELINES, METHODS, PROPOSED, load_config
from cora_maple.protocol import prepare
from cora_maple.runner import run_study, task_directory
from cora_maple.report import report, audit
from cora_maple.learning import predict_neural
from afc_excerpt_ssl.models import PatchEncoder, Classifier


def synthetic_config(tmp_path):
    cfg=load_config(ROOT/'configs/repeated_cv.yaml')
    rng=np.random.default_rng(3477)
    X=rng.integers(0,2,size=(24,4,12),dtype=np.uint8)
    y=np.repeat(np.arange(3),8)
    data=tmp_path/'synthetic.npz'
    np.savez_compressed(data,X=X,y=y,ids=np.array([f'test-source-{i}' for i in range(24)]),tags=np.array(['a','b','c','d']))
    cfg['data'].update(path=str(data),expected_recordings=24,expected_channels=4,observation_samples=12)
    cfg['cv'].update(n_splits=2,n_repeats=1)
    cfg['model'].update(d_model=8,n_layers=1)
    cfg['training'].update(crop_lengths=[6,12],pretrain_batch=4,finetune_batch=4,pretrain_warmup=1,finetune_warmup=1,log_interval=1)
    cfg['training']['schedules']={'excerpt':{'pretrain_steps':2,'finetune_steps':2},'full':{'pretrain_steps':3,'finetune_steps':3}}
    cfg['test'].update(severities=[0.,.3,.5],draws=1,inference_batch=12)
    cfg['study'].update(label_budgets=[1,2])
    return cfg


def test_complete_clean_only_history_export_and_prediction_replay(tmp_path):
    cfg=synthetic_config(tmp_path)
    work=tmp_path/'workspace'
    plan=prepare(cfg,work)
    assert plan['counts']=={'pretrain':8,'fit':24,'baseline':20}
    result=run_study(cfg,work,workers=1,threads=1)
    assert result['complete']
    assert audit(work,'primary')['complete']
    summary=report(work,'primary')
    assert summary['metric_rows']==44*13
    # Exact replay from one real trained checkpoint with reduced-length inputs.
    task=next(t for t in plan['tasks'].values() if t['kind']=='fit' and t['method']=='cora_maple_full')
    directory=task_directory(work,task['id'])
    ckpt=torch.load(directory/'classifier.pt',weights_only=True,map_location='cpu')
    model=Classifier(PatchEncoder(ckpt['n_tags'],**ckpt['model']),ckpt['n_classes'])
    model.load_state_dict(ckpt['state_dict'])
    cachepath=work/json.loads((directory/'evaluation.json').read_text())['test_cache']
    with np.load(cachepath,allow_pickle=False) as cache,np.load(directory/'predictions.npz',allow_pickle=False) as saved:
        for i,x in enumerate(cache['X']):
            assert np.array_equal(predict_neural(model,x,'cpu',12,cache['lengths'][i]),saved['predictions'][i])
    # Actual training statistics prove SSL/S exposures follow each clean-only arm.
    for t in plan['tasks'].values():
        if t['kind']=='baseline':continue
        stats=json.loads((task_directory(work,t['id'])/'training.json').read_text())
        method=METHODS[t['method']]
        assert stats['max_training_severity_observed']<=.30
        if t['kind']=='pretrain':
            allowed=set(cfg['corruption']['pretraining']['operators'])|{'clean'} if method['corruption'] else {'clean'}
        else:
            allowed=set()
            assert method['augmentation']=='none'
            assert stats['corrupted_sample_steps']==0
            assert stats['max_training_severity_observed']==0
        assert set(stats['operator_exposures'])<=allowed
        assert 'missing' not in stats['operator_exposures'] and 'spurious' not in stats['operator_exposures']
    pcfg=deepcopy(cfg)
    pcfg['study'].update(name='pool_sizes',kind='pool',methods=list(PROPOSED),label_budgets=[1],pool_sizes=[1,'full'],pool_draws=[0,1])
    pp=prepare(pcfg,work)
    common=set(pp['tasks'])&set(plan['tasks'])
    assert len(common)==8 # 4 pretraining and 4 k=1 full-pool classifier tasks
    r=run_study(pcfg,work,workers=1,threads=1)
    assert r['complete'] and r['newly_executed_tasks']==16
    report(work,'pool_sizes')
    from cora_maple.__main__ import main
    destination=tmp_path/'paper'
    main(['export-paper','--workspace',str(work),'--destination',str(destination)])
    for f in ['robustness_all_table.tex','robustness_main_table.tex','ablation_factorial_table.tex','unlabelled_pool_table_compact.tex','unlabelled_pool_by_group.tex']:
        assert (destination/'tables'/f).exists()
    assert (destination/'figures/figure1_two_columns.pdf').exists()
    assert (destination/'figures/all_six_robustness_profiles.pdf').exists()
    assert json.loads((destination/'RESULTS_STATUS.json').read_text())['n_splits']==2
    assert json.loads((destination/'RESULTS_STATUS.json').read_text())['protocol']==cfg['protocol']
    table=(destination/'tables/robustness_all_table.tex').read_text()
    assert table.count('$^{P}$')==3 and table.count('$^{U}$')==3
    assert r'Late start$^{U}$' in table
    assert 'Clean CE' not in table  # Stage descriptions belong to the ablation table.
    ablations=(destination/'tables/ablation_factorial_table.tex').read_text()
    assert ablations.count('Clean CE')==6 and 'Paired CE' not in ablations
    from cora_maple.config import operator_groups
    assert operator_groups(cfg)['test_only']==['late_start','missing','spurious']
    assert run_study(cfg,work)['newly_executed_tasks']==0
    # Input-effect summaries are source-level, not spuriously multiplied by model count.
    eff=pd.read_csv(work/'reports/primary/test_input_effects_per_source.csv')
    assert len(eff)==2*12*13
    assert not eff.duplicated(['repeat','fold','source_id','operator','severity','draw']).any()
    import importlib.util
    path=ROOT/'scripts/export_recorded_results.py'
    spec=importlib.util.spec_from_file_location('recorded_complete',path)
    mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    for study in ['primary','pool_sizes']:
        saved_cfg,saved_summary,splits,check=mod.validate_report(work/'reports'/study)
        assert check['complete'] and saved_cfg['protocol']==cfg['protocol']



def test_spawn_workers_and_source_settings_preserve_resume(tmp_path):
    cfg=synthetic_config(tmp_path)
    cfg['study'].update(name='spawn_test',kind='diagnostic',methods=['scratch_excerpt','cora_maple_excerpt'],label_budgets=[1])
    work=tmp_path/'spawn_workspace'
    out=run_study(cfg,work,workers=2,threads=1)
    assert out['complete'] and audit(work,'spawn_test')['complete']
    assert run_study(cfg,work,workers=1)['newly_executed_tasks']==0


def test_recorded_export_rejects_unmatched_protocol(tmp_path):
    import importlib.util
    path=ROOT/'scripts/export_recorded_results.py'
    spec=importlib.util.spec_from_file_location('recorded_export',path)
    mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    folder=tmp_path/'unmatched';folder.mkdir()
    (folder/'REPORT_STATUS.json').write_text(json.dumps({'complete':True,'protocol':'incompatible_protocol'}))
    unmatched=synthetic_config(tmp_path);unmatched['protocol']='incompatible_protocol'
    (folder/'config.json').write_text(json.dumps(unmatched))
    import pytest
    with pytest.raises(ValueError,match='Protocol mismatch'):
        mod.validate_report(folder)
